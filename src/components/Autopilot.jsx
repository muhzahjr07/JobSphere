import React, { useState, useEffect } from 'react';
import { 
  Zap, ZapOff, Settings, FileCheck, Play, Pause, Terminal, Check, X
} from 'lucide-react';

export default function Autopilot({ profile, applications, setApplications }) {
  const [active, setActive] = useState(false);
  const [roleInput, setRoleInput] = useState('DevOps Engineer');
  const [locationInput, setLocationInput] = useState('Remote');
  const [salaryLimit, setSalaryLimit] = useState(2000);
  const [dailyLimit, setDailyLimit] = useState(15);
  
  // Stats
  const [stats, setStats] = useState({
    found: 142,
    applied: 38,
    responses: 6,
    interviews: 2
  });

  // Simulator Logs
  const [logs, setLogs] = useState([
    "System booted. Autopilot Agent in standby.",
    "Ready to search DevOps roles matching LKR 180,000+ / $2,000+ floor."
  ]);

  // Mock pending approvals
  const [pendingApprovals, setPendingApprovals] = useState([
    {
      id: 'app-p-1',
      title: 'Site Reliability Engineer',
      company: 'Sysco Labs',
      salary: '$2,400/mo',
      matchScore: 92,
      recruiter: 'Alex Mercer',
      emailSubject: 'Application for SRE - Mohammed Zaharan'
    },
    {
      id: 'app-p-2',
      title: 'DevOps Associate',
      company: 'Virtusa Sri Lanka',
      salary: 'LKR 200,000',
      matchScore: 84,
      recruiter: 'Kumara de Silva',
      emailSubject: 'Application for DevOps Associate'
    }
  ]);

  useEffect(() => {
    if (!active) return;

    // Simulate logs running in the background
    const interval = setInterval(() => {
      const phrases = [
        "Searching Remote DevOps boards...",
        "Found new job match at Axiata Digital (90% Match)...",
        "Evaluating candidate profile alignment with Kubernetes requirements...",
        "Drafting personalized cover letter focusing on AWS & Linux strengths...",
        "Preparing package: CV, Cover Letter, Outreach Email...",
        "Awaiting user validation for Dialog Axiata application.",
        "Scraping Linkedin career portals...",
        "Response parsed from Virtusa recruiter inbox (Assessment request)."
      ];
      
      const randomPhrase = phrases[Math.floor(Math.random() * phrases.length)];
      setLogs(prev => [randomPhrase, ...prev.slice(0, 10)]);

      // Increment stats slightly
      if (Math.random() > 0.6) {
        setStats(prev => ({
          ...prev,
          found: prev.found + Math.floor(Math.random() * 3) + 1,
          applied: prev.applied + (Math.random() > 0.8 ? 1 : 0)
        }));
      }
    }, 4500);

    return () => clearInterval(interval);
  }, [active]);

  const handleApprove = (app) => {
    // Add to main applications pipeline
    const alreadyApplied = applications.some(a => a.company === app.company && a.title === app.title);
    if (alreadyApplied) {
      alert("Application already added to pipeline.");
      setPendingApprovals(prev => prev.filter(p => p.id !== app.id));
      return;
    }

    const newApp = {
      id: `app-auto-${Date.now()}`,
      jobId: app.id || 'job-auto',
      title: app.title,
      company: app.company,
      location: 'Remote / Colombo',
      salary: app.salary,
      matchScore: app.matchScore,
      status: 'applied',
      appliedDate: new Date().toLocaleDateString(),
      notes: 'Submitted via Autopilot AI Agent.',
      contact: app.recruiter,
      contactEmail: `${app.recruiter.toLowerCase().replace(' ', '')}@${app.company.toLowerCase().replace(/[^a-z]/g, '')}.com`,
      coverLetter: `Generated by JobSphere Autopilot for ${app.company}.`,
      emailDraft: `Subject: ${app.emailSubject}\n\nDear ${app.recruiter},\n\nPlease find my application attached.`
    };

    setApplications([...applications, newApp]);
    setPendingApprovals(prev => prev.filter(p => p.id !== app.id));
    setStats(prev => ({ ...prev, applied: prev.applied + 1 }));
    setLogs(prev => [`✓ Approved & Submitted application for ${app.title} at ${app.company}.`, ...prev]);
  };

  const handleReject = (appId, comp) => {
    setPendingApprovals(prev => prev.filter(p => p.id !== appId));
    setLogs(prev => [`✗ Discarded ${comp} job candidate proposal from queue.`, ...prev]);
  };

  if (!profile) {
    return (
      <div className="panel-body">
        <div className="glass-card" style={{ padding: '40px', textAlign: 'center' }}>
          <h3>Profile Not Created</h3>
          <p style={{ color: 'var(--text-secondary)', fontSize: '14px', marginTop: '8px' }}>
            Initialize your profile to configure your Autopilot job search assistant.
          </p>
        </div>
      </div>
    );
  }

  return (
    <div className="panel-body">
      <div style={{ textAlign: 'left' }}>
        <h3 style={{ fontSize: '18px', fontWeight: '600', marginBottom: '4px' }}>AI Autopilot Cockpit</h3>
        <p style={{ fontSize: '12px', color: 'var(--text-secondary)', marginBottom: '16px' }}>
          Autonomously search, score, and draft applications. You review and release.
        </p>
      </div>

      <div style={{ display: 'grid', gridTemplateColumns: '1.2fr 1.8fr', gap: '24px', textAlign: 'left', alignItems: 'flex-start' }}>
        
        {/* Left: Configuration & Controls */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '20px' }}>
          {/* Main Toggle */}
          <div className="glass-card" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <div>
              <div style={{ fontWeight: 'bold', fontSize: '14px', display: 'flex', alignItems: 'center', gap: '6px' }}>
                {active ? (
                  <Zap className="autopilot-pulse" style={{ color: 'var(--color-primary)' }} />
                ) : (
                  <ZapOff style={{ color: 'var(--text-muted)' }} />
                )}
                <span>Agent Status: {active ? 'ACTIVE' : 'STANDBY'}</span>
              </div>
              <span style={{ fontSize: '11px', color: 'var(--text-secondary)', marginTop: '2px', display: 'block' }}>
                {active ? 'Continuous matching loops running.' : 'Standby. Click Start to run matching.'}
              </span>
            </div>

            <button 
              className="btn-primary" 
              style={{ background: active ? 'var(--color-danger)' : 'var(--color-success)', padding: '8px 16px', fontSize: '12px' }}
              onClick={() => {
                setActive(!active);
                setLogs(prev => [`[AGENT] State shifted to ${!active ? 'ACTIVE' : 'STANDBY'}.`, ...prev]);
              }}
            >
              {active ? <Pause style={{ width: '12px', height: '12px' }} /> : <Play style={{ width: '12px', height: '12px' }} />}
              {active ? 'Stop Agent' : 'Start Agent'}
            </button>
          </div>

          {/* Configuration */}
          <div className="glass-card" style={{ display: 'flex', flexDirection: 'column', gap: '12px' }}>
            <div className="glass-card-title">
              <Settings style={{ color: 'var(--text-muted)' }} />
              <span>Target Parameters</span>
            </div>

            <div className="input-group">
              <span className="input-label">Target Role Keyword</span>
              <input 
                type="text" 
                className="text-input" 
                style={{ padding: '8px 12px', fontSize: '12px' }}
                value={roleInput} 
                onChange={(e) => setRoleInput(e.target.value)}
                disabled={active}
              />
            </div>

            <div className="input-group">
              <span className="input-label">Preferred Location</span>
              <input 
                type="text" 
                className="text-input" 
                style={{ padding: '8px 12px', fontSize: '12px' }}
                value={locationInput} 
                onChange={(e) => setLocationInput(e.target.value)}
                disabled={active}
              />
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '12px' }}>
              <div className="input-group">
                <span className="input-label">Min Salary ($ or LKR)</span>
                <input 
                  type="number" 
                  className="text-input" 
                  style={{ padding: '8px 12px', fontSize: '12px' }}
                  value={salaryLimit} 
                  onChange={(e) => setSalaryLimit(Number(e.target.value))}
                  disabled={active}
                />
              </div>
              <div className="input-group">
                <span className="input-label">Apply Limit (per day)</span>
                <input 
                  type="number" 
                  className="text-input" 
                  style={{ padding: '8px 12px', fontSize: '12px' }}
                  value={dailyLimit} 
                  onChange={(e) => setDailyLimit(Number(e.target.value))}
                  disabled={active}
                />
              </div>
            </div>
          </div>

          {/* Autopilot Stats */}
          <div className="glass-card">
            <div style={{ fontSize: '11px', color: 'var(--text-muted)', textTransform: 'uppercase', marginBottom: '12px' }}>Daily Agent Report</div>
            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '12px' }}>
              <div style={{ background: 'rgba(255,255,255,0.01)', border: '1px solid var(--border-color)', padding: '10px', borderRadius: '6px' }}>
                <span style={{ fontSize: '10px', color: 'var(--text-secondary)' }}>Found</span>
                <div style={{ fontSize: '18px', fontWeight: 'bold', fontFamily: 'var(--font-mono)' }}>{stats.found}</div>
              </div>
              <div style={{ background: 'rgba(255,255,255,0.01)', border: '1px solid var(--border-color)', padding: '10px', borderRadius: '6px' }}>
                <span style={{ fontSize: '10px', color: 'var(--text-secondary)' }}>Applications</span>
                <div style={{ fontSize: '18px', fontWeight: 'bold', fontFamily: 'var(--font-mono)' }}>{stats.applied}</div>
              </div>
              <div style={{ background: 'rgba(255,255,255,0.01)', border: '1px solid var(--border-color)', padding: '10px', borderRadius: '6px' }}>
                <span style={{ fontSize: '10px', color: 'var(--text-secondary)' }}>Recruiter Replies</span>
                <div style={{ fontSize: '18px', fontWeight: 'bold', fontFamily: 'var(--font-mono)' }}>{stats.responses}</div>
              </div>
              <div style={{ background: 'rgba(255,255,255,0.01)', border: '1px solid var(--border-color)', padding: '10px', borderRadius: '6px' }}>
                <span style={{ fontSize: '10px', color: 'var(--text-secondary)' }}>Interviews Scheduled</span>
                <div style={{ fontSize: '18px', fontWeight: 'bold', fontFamily: 'var(--font-mono)', color: 'var(--color-success)' }}>{stats.interviews}</div>
              </div>
            </div>
          </div>
        </div>

        {/* Right: Pending Approvals & Live Console */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '20px' }}>
          
          {/* Pending queue */}
          <div className="glass-card">
            <div className="glass-card-title">
              <FileCheck style={{ color: 'var(--color-primary)' }} />
              <span>Awaiting Validation ({pendingApprovals.length})</span>
            </div>
            
            {pendingApprovals.length === 0 ? (
              <div style={{ padding: '20px', textAlign: 'center', color: 'var(--text-secondary)', fontSize: '12px' }}>
                Queue clear. Agent is searching for matching jobs...
              </div>
            ) : (
              <div style={{ display: 'flex', flexDirection: 'column', gap: '12px' }}>
                {pendingApprovals.map(app => (
                  <div key={app.id} style={{ border: '1px solid var(--border-color)', background: 'var(--bg-input)', padding: '12px', borderRadius: '8px', display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
                    <div>
                      <div style={{ fontSize: '13px', fontWeight: 'bold' }}>{app.title}</div>
                      <div style={{ fontSize: '11px', color: 'var(--text-secondary)', marginTop: '2px' }}>{app.company} • {app.salary}</div>
                      <div style={{ fontSize: '10px', color: '#10b981', marginTop: '4px', fontWeight: 'bold' }}>{app.matchScore}% Match Score</div>
                    </div>

                    <div style={{ display: 'flex', gap: '8px' }}>
                      <button 
                        className="control-btn" 
                        style={{ background: 'rgba(16, 185, 129, 0.15)', borderColor: 'rgba(16, 185, 129, 0.3)', color: '#34d399', padding: '6px' }}
                        onClick={() => handleApprove(app)}
                      >
                        <Check style={{ width: '14px', height: '14px' }} />
                      </button>
                      <button 
                        className="control-btn" 
                        style={{ background: 'rgba(239, 68, 68, 0.15)', borderColor: 'rgba(239, 68, 68, 0.3)', color: '#fca5a5', padding: '6px' }}
                        onClick={() => handleReject(app.id, app.company)}
                      >
                        <X style={{ width: '14px', height: '14px' }} />
                      </button>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>

          {/* Console Output */}
          <div className="glass-card" style={{ display: 'flex', flexDirection: 'column', gap: '12px' }}>
            <div className="glass-card-title">
              <Terminal style={{ color: 'var(--color-primary)' }} />
              <span>Agent Live Terminal Output</span>
            </div>

            <div style={{ 
              background: '#07070a', border: '1px solid var(--border-color)', 
              borderRadius: '8px', padding: '12px', height: '180px', overflowY: 'auto', 
              fontFamily: 'var(--font-mono)', fontSize: '11px', color: '#a78bfa',
              display: 'flex', flexDirection: 'column', gap: '8px'
            }}>
              {logs.map((log, idx) => (
                <div key={idx} style={{ 
                  color: log.startsWith('✓') ? '#10b981' : log.startsWith('✗') ? '#ef4444' : log.startsWith('[') ? '#e9d5ff' : '#9ca3af' 
                }}>
                  {log}
                </div>
              ))}
            </div>
          </div>
        </div>

      </div>
    </div>
  );
}
